import { usePredictionExplanation } from '../../hooks/usePredictionMutations'
import type { Tier } from '../../types/prediction'

export function LlmSummaryCard({ id, tier }: { id: number; tier: Tier | 'legacy' }) {
  const { data, isLoading, isError } = usePredictionExplanation(String(id), tier !== 'legacy')

  if (tier === 'legacy') return null

  return (
    <div className="rounded-lg border border-slate-200 p-4 dark:border-slate-800">
      <h2 className="text-sm font-semibold text-slate-800 dark:text-slate-100">
        AI-Generated Summary
      </h2>

      {isLoading && (
        <div className="mt-2 space-y-2">
          <div className="h-3 w-full animate-pulse rounded bg-slate-100 dark:bg-slate-800" />
          <div className="h-3 w-5/6 animate-pulse rounded bg-slate-100 dark:bg-slate-800" />
          <div className="h-3 w-2/3 animate-pulse rounded bg-slate-100 dark:bg-slate-800" />
        </div>
      )}

      {isError && (
        <p className="mt-2 text-sm text-slate-500 dark:text-slate-400">
          AI explanation is temporarily unavailable. The risk score and factors above are
          unaffected.
        </p>
      )}

      {data && (
        <>
          <p className="mt-2 text-sm text-slate-700 dark:text-slate-200">{data.llm_summary}</p>
          <p className="mt-4 text-xs text-slate-400">
            This summary was generated by an AI model from the risk estimate above. Research
            prototype — not a medical diagnosis, not clinically validated.
          </p>
        </>
      )}
    </div>
  )
}
